package com.example.spotify.models;

public class Nghesi {
    private String ten, avt;

    public Nghesi(String ten, String avt) {
        this.ten = ten;
        this.avt = avt;
    }

    public String getTen() {
        return ten;
    }

    public void setTen(String ten) {
        this.ten = ten;
    }

    public String getAvt() {
        return avt;
    }

    public void setAvt(String avt) {
        this.avt = avt;
    }
}
